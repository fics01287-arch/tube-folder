// 제3자 오픈소스 라이선스 고지 생성·검사 스크립트 (규칙 원본: 공통지침 '제3자 라이선스 고지 지침.txt')
// 의존성 추가 없음(Node 표준 모듈만 사용). 같은 입력(package-lock.json·node_modules의 LICENSE 파일)이면 같은 결과가 나온다(시각 미포함).
//
// 사용법
//   node scripts/make-notices.mjs                          → public/THIRD_PARTY_NOTICES.txt 생성(vite가 dist·pwa-dist로 복사)
//   node scripts/make-notices.mjs --check                  → 고지 파일이 최신인지, 직접 의존성이 빠지지 않았는지 검사(빌드 전)
//   node scripts/make-notices.mjs --check --dist dist:manager,background,content
//                                                          → 위 검사 + 빌드 결과물에 고지 파일이 들어갔는지 + build-report/<이름>.json(실제 번들에 든 패키지)이
//                                                            모두 고지에 있는지 검사(빌드 후). --dist 는 여러 번 쓸 수 있음.
//
// 고지 대상 = 아래 NOTICE_PACKAGES. 새 라이브러리가 번들에 들어오면 --dist 검사가 실패해 여기에 추가하도록 강제한다.
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// ── 앱별 설정: 이 블록만 앱에 맞게 고친다 ─────────────────────────────
const APP_NAME = 'TubeFolder (튜브폴더)';
// 실제 번들(dist 매니저·PWA)에 들어가는 제3자 패키지. 근거: build-report(Rollup이 출력한 모듈) + package-lock.json.
// production 의존성 중 tslib·js-tokens·loose-envify는 하위 의존이지만 번들에 들어가지 않아 제외했다(2026-11-18 빌드 분석).
const NOTICE_PACKAGES = [
  '@dnd-kit/accessibility',
  '@dnd-kit/core',
  '@dnd-kit/sortable',
  '@dnd-kit/utilities',
  '@tanstack/react-virtual',
  '@tanstack/virtual-core',
  'react',
  'react-dom',
  'scheduler'
];
const OUT_REL = 'public/THIRD_PARTY_NOTICES.txt';
const FILE_NAME = 'THIRD_PARTY_NOTICES.txt';
// ────────────────────────────────────────────────────────────────────

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const check = argv.includes('--check');
const distTargets = [];
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--dist' && argv[i + 1]) {
    const [dir, reports] = argv[i + 1].split(':');
    distTargets.push({ dir, reports: (reports || '').split(',').filter(Boolean) });
    i++;
  }
}
const errors = [];
const fail = (m) => errors.push(m);

const pkgJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8')).packages || {};

// 1) 직접 production 의존성이 고지 목록에 있는지(새 직접 의존성을 추가하고 고지를 잊는 실수 방지)
for (const dep of Object.keys(pkgJson.dependencies || {})) {
  if (!NOTICE_PACKAGES.includes(dep)) fail(`[목록 누락] package.json의 dependencies '${dep}'가 scripts/make-notices.mjs의 NOTICE_PACKAGES에 없습니다 — 고지 대상인지 확인하고 추가하세요.`);
}

function licenseFileOf(name) {
  const dir = join(root, 'node_modules', ...name.split('/'));
  if (!existsSync(dir)) return null;
  const cands = readdirSync(dir).filter((f) => /^(licen[sc]e|copying)(\.[a-z]+)?$/i.test(f));
  cands.sort((a, b) => (/^licen[sc]e$/i.test(b) ? 1 : 0) - (/^licen[sc]e$/i.test(a) ? 1 : 0) || a.localeCompare(b));
  return cands.length ? join(dir, cands[0]) : null;
}
function repoUrlOf(name) {
  try {
    const p = JSON.parse(readFileSync(join(root, 'node_modules', ...name.split('/'), 'package.json'), 'utf8'));
    let u = typeof p.repository === 'string' ? p.repository : p.repository && p.repository.url;
    if (!u && p.homepage) u = p.homepage;
    if (!u) return '(원본 주소 없음)';
    return u.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git$/, '');
  } catch { return '(원본 주소 확인 불가)'; }
}

const entries = [];
for (const name of [...NOTICE_PACKAGES].sort()) {
  const meta = lock['node_modules/' + name];
  if (!meta) { fail(`[lock 없음] ${name} — package-lock.json에 없습니다(제거된 의존성이면 NOTICE_PACKAGES에서도 빼세요).`); continue; }
  const lf = licenseFileOf(name);
  if (!lf) { fail(`[원문 없음] node_modules/${name} 안에서 LICENSE 파일을 찾지 못했습니다(npm ci 후 다시 실행하세요).`); continue; }
  const text = readFileSync(lf, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n').trim();
  entries.push({ name, version: meta.version, license: meta.license || '(표기 없음)', url: repoUrlOf(name), text });
}

function render() {
  const L = [];
  L.push(`${APP_NAME} — 오픈소스 라이선스 고지 / Third-Party Notices`);
  L.push('');
  L.push('이 앱은 아래 오픈소스 구성요소를 포함합니다. 각 구성요소의 저작권 표시와 라이선스 전문을 아래에 실었습니다.');
  L.push('원본 주소에서 소스를 받을 수 있습니다. 이 파일은 scripts/make-notices.mjs가 만들며, 구성요소가 바뀌면 다시 만듭니다.');
  L.push('');
  L.push('This application includes the open-source components listed below. The copyright notice and the full license text of each component are reproduced');
  L.push('after the list. Source code is available at each original address. This file is generated by scripts/make-notices.mjs and regenerated whenever components change.');
  L.push('');
  L.push(`구성요소 / Components (${entries.length})`);
  entries.forEach((e, i) => L.push(`${String(i + 1).padStart(2, ' ')}. ${e.name} ${e.version} — ${e.license} — ${e.url}`));
  for (const e of entries) {
    L.push('');
    L.push('='.repeat(78));
    L.push(`${e.name} ${e.version}`);
    L.push(`License: ${e.license}`);
    L.push(`Source: ${e.url}`);
    L.push('='.repeat(78));
    L.push('');
    L.push(e.text);
  }
  L.push('');
  return '﻿' + L.join('\n');
}

if (errors.length === 0) {
  const body = render();
  const outAbs = join(root, OUT_REL);
  if (!check) {
    writeFileSync(outAbs, body, 'utf8');
    console.log(`[notices] ${OUT_REL} 생성 — 구성요소 ${entries.length}개`);
  } else {
    if (!existsSync(outAbs)) fail(`[없음] ${OUT_REL} — 'npm run notices'로 만드세요.`);
    else if (readFileSync(outAbs, 'utf8') !== body) fail(`[오래됨] ${OUT_REL}이 현재 의존성(package-lock.json·node_modules)과 다릅니다 — 'npm run notices'로 다시 만드세요.`);
    else console.log(`[notices] 소스 OK — 고지 파일이 최신입니다(구성요소 ${entries.length}개).`);

    // 2) 빌드 결과물 검사(--dist)
    for (const { dir, reports } of distTargets) {
      const absDir = join(root, dir);
      if (!existsSync(absDir)) { fail(`[결과물 없음] ${dir} 폴더가 없습니다 — 빌드가 먼저 끝나야 합니다.`); continue; }
      const inDist = join(absDir, FILE_NAME);
      if (!existsSync(inDist)) fail(`[배포물 누락] ${dir}/${FILE_NAME}이 없습니다 — public/ 복사가 빠졌습니다.`);
      else if (readFileSync(inDist, 'utf8') !== body) fail(`[배포물 불일치] ${dir}/${FILE_NAME}이 ${OUT_REL}과 다릅니다.`);
      const bundled = new Set();
      for (const r of reports) {
        const rp = join(root, 'build-report', r + '.json');
        if (!existsSync(rp)) { fail(`[보고서 없음] build-report/${r}.json이 없습니다 — 빌드에 scripts/bundleReport.mjs 플러그인이 연결돼 있어야 합니다.`); continue; }
        for (const p of Object.keys(JSON.parse(readFileSync(rp, 'utf8')).packages || {})) bundled.add(p);
      }
      const missing = [...bundled].filter((p) => !NOTICE_PACKAGES.includes(p));
      if (missing.length) fail(`[고지 누락] ${dir} 번들에 들어간 패키지가 고지에 없습니다: ${missing.join(', ')} — NOTICE_PACKAGES에 추가하고 'npm run notices'를 실행하세요.`);
      else if (reports.length && !errors.length) console.log(`[notices] 빌드 결과물 OK — ${dir}: 고지 파일 포함, 번들 패키지 ${bundled.size}개 모두 고지에 있음.`);
    }
  }
}

if (errors.length) {
  console.error('\n❌ 제3자 라이선스 고지 검사 실패 — 빌드를 중단합니다.');
  for (const e of errors) console.error('  - ' + e);
  console.error('\n해결: 공통지침 \'제3자 라이선스 고지 지침.txt\' §3·§6을 따르거나 Claude에게 "고지 갱신해줘"라고 요청하세요.\n');
  process.exit(1);
}
